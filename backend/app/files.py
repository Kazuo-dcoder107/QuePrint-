"""Controlled upload: extension + signature + size + structure checks, then page counting.
DOCX files are converted to PDF with LibreOffice (headless) so the page count is real and the
PDF is what gets printed."""
import re, shutil, subprocess, tempfile, uuid, zipfile
from pathlib import Path
from fastapi import HTTPException, UploadFile
from pypdf import PdfReader
from . import config

ALLOWED = {".pdf": b"%PDF-", ".docx": b"PK\x03\x04"}
PDF_RISKY = re.compile(rb"/(JavaScript|JS|Launch|EmbeddedFile)\b")
MAX_BYTES = config.MAX_UPLOAD_MB * 1024 * 1024


def bad(msg: str):
    raise HTTPException(422, msg)


def safe_display_name(name: str) -> str:
    name = Path(name or "document").name
    return re.sub(r"[^\w .()\-]", "_", name)[:200] or "document"


def _save_limited(upload: UploadFile, dest: Path):
    size = 0
    with open(dest, "wb") as out:
        while chunk := upload.file.read(1024 * 1024):
            size += len(chunk)
            if size > MAX_BYTES:
                out.close(); dest.unlink(missing_ok=True)
                bad(f"File is too large. The limit is {config.MAX_UPLOAD_MB} MB.")
            out.write(chunk)
    if size == 0:
        dest.unlink(missing_ok=True)
        bad("The file is empty.")
    return size


def _check_pdf(path: Path, scan: bool = True) -> int:
    if scan and PDF_RISKY.search(path.read_bytes()):
        bad("This PDF contains scripts or embedded content and was rejected for safety.")
    try:
        reader = PdfReader(str(path))
        if reader.is_encrypted:
            bad("Password-protected PDFs are not accepted. Remove the password and upload again.")
        return len(reader.pages)
    except HTTPException:
        raise
    except Exception:
        bad("This PDF is corrupted or unreadable.")


def _check_docx(path: Path):
    try:
        with zipfile.ZipFile(path) as z:
            names = z.namelist()
            if "[Content_Types].xml" not in names or "word/document.xml" not in names:
                bad("This is not a valid Word (.docx) document.")
            if any(n.lower().endswith(("vbaproject.bin", ".exe", ".dll", ".js", ".vbs")) for n in names):
                bad("This document contains macros or executable content and was rejected for safety.")
            if sum(i.file_size for i in z.infolist()) > 300 * 1024 * 1024:
                bad("This document expands to an unsafe size.")
    except zipfile.BadZipFile:
        bad("This Word document is corrupted.")


def _docx_to_pdf(src: Path, out_dir: Path) -> Path:
    exe = shutil.which("soffice") or shutil.which("libreoffice")
    if not exe:
        raise HTTPException(503, "Word conversion is unavailable on the server. Please upload a PDF instead.")
    with tempfile.TemporaryDirectory() as profile:
        try:
            subprocess.run([exe, f"-env:UserInstallation=file://{profile}", "--headless", "--norestore",
                            "--convert-to", "pdf", "--outdir", str(out_dir), str(src)],
                           check=True, capture_output=True, timeout=120)
        except Exception:
            bad("We could not read this Word document. Try saving it as PDF and upload again.")
    pdf = out_dir / (src.stem + ".pdf")
    if not pdf.exists():
        bad("We could not convert this Word document. Try saving it as PDF and upload again.")
    return pdf


def _clamscan(path: Path):
    if not config.CLAMSCAN:
        return
    exe = shutil.which("clamscan")
    if not exe:
        return
    r = subprocess.run([exe, "--no-summary", str(path)], capture_output=True, timeout=120)
    if r.returncode == 1:
        path.unlink(missing_ok=True)
        bad("The antivirus scan flagged this file. It was rejected.")


def store_upload(upload: UploadFile) -> dict:
    """Validate and store an uploaded file. Returns info needed to create a draft job."""
    display = safe_display_name(upload.filename)
    ext = Path(display).suffix.lower()
    if ext not in ALLOWED:
        bad("Only PDF and DOCX files are accepted.")
    config.UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    stem = uuid.uuid4().hex
    src = config.UPLOAD_DIR / f"{stem}{ext}"
    size = _save_limited(upload, src)
    keep = [src]
    try:
        with open(src, "rb") as f:
            if f.read(len(ALLOWED[ext])) != ALLOWED[ext]:
                bad("The file contents do not match its extension.")
        _clamscan(src)
        if ext == ".pdf":
            pages, print_path = _check_pdf(src), src
        else:
            _check_docx(src)
            print_path = _docx_to_pdf(src, config.UPLOAD_DIR)
            keep.append(print_path)
            pages = _check_pdf(print_path, scan=False)  # generated by our own converter
        if pages < 1 or pages > config.MAX_PAGES:
            bad(f"Documents must be between 1 and {config.MAX_PAGES} pages.")
        return {"original_name": display, "stored_name": src.name, "print_name": print_path.name,
                "file_size": size, "page_count": pages}
    except Exception:
        for p in keep:
            p.unlink(missing_ok=True)
        raise


def remove_files(*names: str):
    for n in set(names):
        (config.UPLOAD_DIR / n).unlink(missing_ok=True)
